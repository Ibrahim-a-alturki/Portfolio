-- ============================================================
-- Vehicle Insurance Portal — Malath Insurance
-- File: triggers.sql
-- Description: Automation triggers for the Vehicle Insurance
--              Portal database.
--
--              1) Business logic trigger — automatically
--                 activates a Policy once its Payment is
--                 recorded.
--              2) Audit-trail triggers — applied identically
--                 across all six core tables (Owner, Policy,
--                 Vehicle, Coverage, Payments, Claims) to track
--                 who created/modified each record and when:
--                   - CreationBY        (set on INSERT)
--                   - CreationDate      (set on INSERT)
--                   - ModifiedBY        (set on UPDATE)
--                   - LastModifiedDate  (set on UPDATE)
--
-- Total: 25 triggers (6 tables x 4 audit triggers + 1 policy
--        activation trigger), matching the deployed schema.
-- ============================================================


-- ------------------------------------------------------------
-- 1. Business Logic Trigger: Auto-activate policy on payment
-- ------------------------------------------------------------

DROP TRIGGER ITURKI.TRG_UPDATE_PLICY_STATUS;

CREATE OR REPLACE TRIGGER ITURKI.TRG_UPDATE_Plicy_Status
AFTER INSERT ON ITURKI.PAYMENTS
FOR EACH ROW
BEGIN
    UPDATE policy
    SET Policy_Status = 'Active'
    WHERE Policy_ID = :NEW.Policy_ID;
END;
/


