-- === CLAIMS ===

DROP TRIGGER ITURKI.UPDATECLAIMS_TIMESTAMP;
CREATE OR REPLACE TRIGGER ITURKI.UPDATECLAIMS_TIMESTAMP
BEFORE UPDATE ON ITURKI.Claims
FOR EACH ROW
BEGIN
    :NEW.LastModifiedDate := CURRENT_TIMESTAMP;
END;
/

